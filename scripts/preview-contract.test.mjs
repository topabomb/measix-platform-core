import { test } from 'node:test'
import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import { snapshotVersions, androidSnapshotVersions } from './lib/harness.mjs'
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, cpSync, rmSync } from 'node:fs'
import { spawnSync } from 'node:child_process'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
import { androidContractFailures } from './verify-preview-contract.mjs'
import { platformContractIdentity } from './lib/release-contract.mjs'

const schema = Buffer.from('openapi: 3.0.3\ncomponents: {}\n')
const digest = createHash('sha256').update(schema).digest('hex')
const manifest = { generated: true, source: '../api/client/client-control.openapi.yaml', sourceHash: `sha256:${digest}`, format: 'openapi-3.0.3-client-schema-only' }
const header = `// Generated by tools/generate-enterprise-wire.py\n// Core source SHA256 (LF): ${digest}\n`

test('Android identity accepts the actual generated header and canonical LF schema', () => {
  assert.deepEqual(androidContractFailures(schema, manifest, schema, { ...manifest }, header), [])
})

test('production preview verifier uses the configured Android checkout across different directory layouts', () => {
  const temp = mkdtempSync(join(tmpdir(), 'measix-preview-layout-'))
  const root = join(temp, 'workspace', 'measix-platform-core')
  const customAndroid = join(temp, 'Android Projects', 'Measix_Pilot')
  const defaultAndroid = join(temp, 'rikkahub_mcp')
  const put = (base, name, contents) => {
    const file = join(base, name)
    mkdirSync(resolve(file, '..'), { recursive: true })
    writeFileSync(file, contents)
  }
  const json = value => JSON.stringify(value)
  try {
    const actualRoot = resolve(import.meta.dirname, '..')
    put(root, 'scripts/verify-preview-contract.mjs', readFileSync(join(actualRoot, 'scripts/verify-preview-contract.mjs')))
    cpSync(join(actualRoot, 'scripts/lib'), join(root, 'scripts/lib'), { recursive: true })
    const names = ['api/client/client-control.openapi.yaml', 'api/admin/admin.openapi.yaml', 'api/internal/relay-control.openapi.yaml', 'api/internal/usage-ingest.openapi.yaml']
    for (const name of names) put(root, name, schema)
    const baseline = json({ platformContractVersion: 2, supportedPlatformContractVersions: [2], coreBaselineVersion: '0.2.0-preview.23', baseline: 'test', policy: 'test', documents: Object.fromEntries(names.map(name => [name, `sha256:${digest}`])) })
    const identity = platformContractIdentity(Buffer.from(baseline))
    const versionedManifest = { ...manifest, ...identity }
    const portalManifest = { ...identity, bridgeVersion: 3, artifacts: { 'test.json': { source: 'api/portal/test.json', sha256: createHash('sha256').update('{}').digest('hex') } } }
    put(root, 'api/protocol-baseline.json', baseline)
    put(root, 'api/generated/android/protocol-baseline.json', baseline)
    put(root, 'api/portal/test.json', '{}')
    put(root, 'api/generated/android/portal/test.json', '{}')
    put(root, 'api/generated/android/client-control.openapi.yaml', schema)
    put(root, 'api/generated/android/manifest.json', json(versionedManifest))
    put(root, 'api/generated/android/portal/manifest.json', json(portalManifest))
    put(root, 'api/fixtures/client-integration/snapshot-reception-cases.json', '{}')
    put(join(root, '..', 'measix-enterprise-portal'), 'src/api/contract.json', json({ artifacts: {} }))
    for (const android of [customAndroid, defaultAndroid]) {
      put(android, 'app/src/test/resources/contracts/platform/client-control.openapi.yaml', schema)
      put(android, 'app/src/test/resources/contracts/platform/manifest.json', json(android === customAndroid ? versionedManifest : { ...versionedManifest, sourceHash: 'stale' }))
      put(android, 'app/src/test/resources/contracts/platform/snapshot-reception-cases.json', '{}')
      put(android, 'app/src/test/resources/contracts/portal/manifest.json', json(portalManifest))
      put(android, 'app/src/test/resources/contracts/portal/test.json', '{}')
      put(android, 'app/src/main/java/net/weero/measix/pilot/data/enterprise/PlatformWire.kt', header)
    }
    const run = env => spawnSync(process.execPath, [join(root, 'scripts/verify-preview-contract.mjs')], { cwd: root, env, encoding: 'utf8' })
    const overridden = run({ ...process.env, MEASIX_RELEASE_ANDROID_ROOT: customAndroid })
    assert.equal(overridden.status, 0, overridden.stderr)
    // Without an override, the existing default layout remains supported.
    put(defaultAndroid, 'app/src/test/resources/contracts/platform/manifest.json', json(versionedManifest))
    const env = { ...process.env }
    delete env.MEASIX_RELEASE_ANDROID_ROOT
    const fallback = run(env)
    assert.equal(fallback.status, 0, fallback.stderr)
  } finally { rmSync(temp, { recursive: true, force: true }) }
})
test('Android identity rejects independently stale manifest, schema, and generated Kotlin', () => {
  const legacyHeader = `// Source SHA256: ${digest}\n`
  assert.ok(androidContractFailures(schema, manifest, schema, { ...manifest, sourceHash: 'sha256:wrong' }, legacyHeader).some(value => value.includes('manifest')))
  assert.ok(androidContractFailures(schema, manifest, Buffer.from('other schema'), manifest, header).some(value => value.includes('fixture')))
  assert.ok(androidContractFailures(schema, manifest, schema, manifest, header.replace(digest, '0'.repeat(64))).some(value => value.includes('PlatformWire')))
})

test('Android identity normalizes checkout line endings but rejects malformed or mismatched manifests', () => {
  assert.deepEqual(androidContractFailures(schema, manifest, Buffer.from(schema.toString().replaceAll('\n', '\r\n')), manifest, header.replaceAll('\n', '\r\n')), [])
  for (const invalid of [{ ...manifest, generated: false }, { ...manifest, format: 'other' }, { ...manifest, sourceHash: 'sha256:wrong' }]) {
    assert.ok(androidContractFailures(schema, invalid, schema, invalid, header).some(value => value.includes('manifest')))
  }
  assert.ok(androidContractFailures(schema, manifest, schema, { ...manifest, source: 'untrusted-source' }, header).some(value => value.includes('manifest')))
})

test('release Snapshot versions come from the compiler and reject incomplete source identity', () => {
  assert.deepEqual(snapshotVersions(resolve(import.meta.dirname, '..')), { current: 5, supported: [4, 5] })
  const root = mkdtempSync(join(tmpdir(), 'measix-snapshot-identity-'))
  try {
    const directory = join(root, 'backend/internal/hub/capability')
    mkdirSync(directory, { recursive: true })
    const file = join(directory, 'snapshot.go')
    const source = 'const CurrentSnapshotSchemaVersion = 7\nfunc SupportedSnapshotSchemaVersions() []int { return []int{5, 7} }\n'
    writeFileSync(file, source)
    assert.deepEqual(snapshotVersions(root), { current: 7, supported: [5, 7] })
    for (const invalid of ['', source.replace('5, 7', '5'), source.replace('5, 7', '7, 7'), source.replace('5, 7', '5, unknown')]) {
      writeFileSync(file, invalid)
      assert.throws(() => snapshotVersions(root), /Snapshot/)
    }
  } finally { rmSync(root, { recursive: true, force: true }) }
})

test('release records the finite Android support set independently of Core', () => {
  const root = mkdtempSync(join(tmpdir(), 'measix-android-support-'))
  try {
    const directory = join(root, 'app/src/main/java/net/weero/measix/pilot/data/enterprise')
    mkdirSync(directory, { recursive: true })
    const file = join(directory, 'PlatformSnapshotCompatibility.kt')
    const source = 'val supportedSchemas: Set<Long> = setOf(5L, 7L)'
    writeFileSync(file, source)
    assert.deepEqual(androidSnapshotVersions(root), [5, 7])
    for (const invalid of ['', source.replace('5L, 7L', '5L, 5L'), source.replace('5L, 7L', '0L'), source.replace('5L, 7L', 'nextVersion')]) {
      writeFileSync(file, invalid)
      assert.throws(() => androidSnapshotVersions(root), /Android Snapshot/)
    }
  } finally { rmSync(root, { recursive: true, force: true }) }
})
